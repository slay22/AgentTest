// Stamps the deploy version before `wrangler deploy`, mirroring receiptScanner.
// The Worker sends it on the x-deploy-version response header and from
// GET /api/health, so a deploy can always be identified.

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

let sha = 'nosha';
try {
  sha = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .trim();
} catch {
  // Not a git checkout: the timestamp still makes every deploy distinct.
}

const stamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14);
const value = `v${version}-g${sha}-${stamp}`;

writeFileSync(
  join(root, 'src/version.ts'),
  `/** Generated by scripts/write-version.mjs before \`wrangler deploy\`. Do not edit. */\nexport const VERSION = '${value}';\n`,
);
console.log(`version: ${value}`);
